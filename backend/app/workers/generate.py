"""Wada trie executor (TDD §8.8/§8.12, gated by the M7-T1 chain verdict).

wada.generate_colorway walks the planned trie for ONE colorway: per node it
edits the PARENT node's composited image with Seedream (fal queue), then —
gate condition 1 — composites the raw output back through the step's union
mask (+2px dilation, 3px feather) IMMEDIATELY, never lazily at chain end.
Gate condition 2 guards run per node: byte-identity outside the feathered
support (lock_verified — a failure marks the colorway failed and stops that
chain; no silent bad colorways), plus ghost-fraction and in-region median
ΔE2000 logged onto the gen_nodes row.

PARALLEL-1 (2026-07-31): one task per COLORWAY, not one per run. Steps within
a colorway are inherently serial (each step edits the previous step's image),
but colorways are independent once their chains diverge, and every node is a
~39s network-bound fal call — so "generate the remaining N" fans out to N
child tasks on the wada queue and finishes in wall-clock N/concurrency time.
Two things follow, both handled here:

1. Shared prefix nodes must be paid for ONCE. Two colorways whose chains share
   a prefix would otherwise both call the model for the same node. The trie row
   IS the lock: a task INSERTs the gen_nodes row with image_key = '' (the claim
   marker) ON CONFLICT DO NOTHING — one INSERT wins, the loser polls the row and
   takes the winner's image as an ordinary §8.8 cache hit (hit_count++, $0,
   ledgered cache_hit=true). A claim whose owner died (SIGKILL/OOM: no finally
   runs) goes stale after CLAIM_STALE_S and the waiter takes it over rather than
   waiting forever. Failure paths delete their claim, so a failed node is never
   a poisoned cache entry (unchanged from M7: bad artifacts are not cached).
2. The run closes when the LAST child finishes. studies.gen_pending (migration
   0005) is decremented by every child in a finally; the child that drives it to
   zero recomputes the study's terminal status FROM THE COLORWAY ROWS and clears
   the watchdog heartbeat. No in-memory or in-broker state is trusted, and the
   recompute is idempotent, so a double decrement can only close twice.

Cache semantics (§8.8): a gen_nodes row whose image object still exists IS
the node — the model is never called for it (hit_count++, $0, ledgered with
cache_hit=true). Re-running a study therefore resumes/idempotently replays
for free. A row whose object was evicted is treated as a miss and re-filled.

Budget (§8.11): checked before EVERY model call (study cap → daily cap →
hard freeze; config in app.config). A mid-run cap marks the study 'partial'
and keeps everything generated so far — never rolled back. Every model call
is ledgered in spend_ledger with integer cents allocated cumulatively so the
study total always equals round_half_up(6.75¢ × calls) — the exact number
the estimate showed (alloc_cents docstring).

Working base: the study's base media CUTOUT (the Wada contract since the
2026-07-26 PhotoRoom decision) — ensure_cutout() before the first node,
falling back to the original when no cutout can be produced. The working
frame must equal the region-mask frame; a mismatch fails the run loudly.
When a cutout exists, its alpha also drives the residual-coverage pass
(app.wada.coverage): slot masks are grown until their union covers the whole
product silhouette, so no sliver of the ORIGINAL base colour survives the
composite; grown masks are re-uploaded content-addressed under their own sha.
The pass is deterministic pure CV, so every child of a fan-out recomputes
byte-identical grown masks — and therefore identical shas and cache keys.

Documented deviations:
- Anchored slots are painted as real chain steps (shared by every colorway).
  plan_study() excludes anchors from the assignment space, so estimates for
  anchored studies undercount by the anchor steps — flagged for M8.
- colorways.thumb_key = cw/{ws}/{colorway_id}.400.webp (§3 defines no cw
  thumb prefix; kept under cw/ so the pin/export lifecycle finds it).
- The §8.11 per-call check reads the study total per child, so N children can
  each admit one call against the same remaining headroom: a run may overshoot
  the study cap by at most (N_workers − 1) × one call (~7¢). The alternative —
  serialising the ledger behind a study-wide lock — would undo the fan-out.
- A node whose image object was evicted is regenerated by whoever notices,
  without a claim (the row is filled, so nobody would wait on it): concurrent
  children could pay twice for a re-fill. Eviction is a cold-storage event, not
  a hot path, and the ON CONFLICT DO UPDATE keeps the trie consistent.
"""

